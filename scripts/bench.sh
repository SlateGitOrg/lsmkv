#!/usr/bin/env bash
# Runs db_bench at 1M entries on this machine and writes bench/RESULTS.md.
# Usage: scripts/bench.sh [num_entries]
set -euo pipefail
cd "$(dirname "$0")/.."

NUM="${1:-1000000}"
OUT=bench/RESULTS.md
mkdir -p bench/tmp

cargo build --release --quiet --bin db_bench
BIN="${CARGO_TARGET_DIR:-target}/release/db_bench"

cpu="$( (sysctl -n machdep.cpu.brand_string 2>/dev/null || grep -m1 'model name' /proc/cpuinfo | cut -d: -f2) | sed 's/^ *//')"
cores="$( (sysctl -n hw.ncpu 2>/dev/null || nproc) )"
mem="$( (sysctl -n hw.memsize 2>/dev/null | awk '{printf "%.0f GB", $1/1073741824}') || free -g | awk '/Mem:/{print $2" GB"}')"
load="$( (sysctl -n vm.loadavg 2>/dev/null || cut -d' ' -f1-3 /proc/loadavg) | tr -d '{}' | sed 's/^ *//')"

RESULT="$("$BIN" --num="$NUM" --db=bench/tmp/db_bench)"
echo "$RESULT"

{
  echo "# db_bench results"
  echo
  echo "Generated by \`scripts/bench.sh $NUM\` (\`make bench\`) — do not edit by hand."
  echo
  echo "| | |"
  echo "|---|---|"
  echo "| date | $(date -u +%Y-%m-%dT%H:%MZ) |"
  echo "| commit | $(git rev-parse --short HEAD 2>/dev/null || echo unknown) |"
  echo "| cpu | $cpu ($cores logical cores) |"
  echo "| memory | $mem |"
  echo "| os | $(uname -sr) |"
  echo "| rustc | $(rustc --version) |"
  echo "| load average at start | $load |"
  echo "| filesystem | APFS/ext4 via std::fs, fsync = \`File::sync_data\` |"
  echo
  echo '```'
  echo "$RESULT"
  echo '```'
} > "$OUT"
echo "wrote $OUT"
